import type { DiskEntry } from './inspect.js';

/**
 * What `forge update` decides to do about one file.
 *
 * Three hashes describe every file: BASE (what Forge recorded when it last wrote it), DISK (what is there now)
 * and NEXT (what the installed Forge would write today). "Upstream changed it" is NEXT != BASE and "the user
 * changed it" is DISK != BASE. Those are independent, which is what `forge new` cannot express.
 */
export type UpdateKind =
  | 'create' // new upstream file, nothing on disk
  | 'update' // untouched by the user, changed upstream
  | 'unchanged' // nothing to do
  | 'adopt' // identical file already on disk that Forge did not track
  | 'converged' // the user already made the same change as upstream
  | 'keep' // the user edited it and upstream did not change it (or it is create-only)
  | 'kept-removed' // the user deleted it and upstream did not change it
  | 'conflict' // both sides changed it, or an untracked file is in the way
  | 'orphan' // untouched, but the template no longer produces it
  | 'orphan-modified' // edited by the user and no longer produced: now theirs
  | 'gone' // neither tracked nor produced nor present
  | 'blocked'; // a directory or symlink is in the way

/** What the recorded hash in .forge/state.json becomes. */
export type StateHash = 'next' | 'base' | 'drop';

export interface UpdateClassification {
  readonly kind: UpdateKind;
  readonly reason?: string;
  readonly state: StateHash;
}

export interface UpdateInput {
  readonly base: string | undefined;
  readonly disk: DiskEntry;
  readonly next: string | undefined;
  /** `none` files are created once and never updated afterwards. */
  readonly strategy: 'overwrite' | 'none';
}

/** The kinds that write a file. Exported so tests can state the safety property directly. */
export const WRITING_KINDS: ReadonlySet<UpdateKind> = new Set(['create', 'update']);

/** Pure and total: every combination of inputs maps to exactly one outcome. */
export function classifyUpdate(input: UpdateInput): UpdateClassification {
  const { base, disk, next, strategy } = input;
  const tracked = base !== undefined;

  if (disk.kind === 'dir') return { kind: 'blocked', reason: 'a directory exists at this path', state: tracked ? 'base' : 'drop' };
  if (disk.kind === 'blocked') return { kind: 'blocked', reason: disk.reason, state: tracked ? 'base' : 'drop' };

  const onDisk = disk.kind === 'file' ? disk.hash : undefined;

  // The template no longer produces this path.
  if (next === undefined) {
    if (!tracked || onDisk === undefined) return { kind: 'gone', state: 'drop' };
    if (onDisk === base) return { kind: 'orphan', reason: 'the template no longer generates it', state: 'base' };
    return { kind: 'orphan-modified', reason: 'you changed it, so it is yours now', state: 'drop' };
  }

  // Not tracked: Forge never wrote it.
  if (!tracked) {
    if (onDisk === undefined) return { kind: 'create', state: 'next' };
    if (onDisk === next) return { kind: 'adopt', state: 'next' };
    return { kind: 'conflict', reason: 'exists and was not generated by Forge', state: 'drop' };
  }

  // Create-only files are never touched again once they exist.
  if (strategy === 'none') {
    if (onDisk === undefined) return { kind: 'kept-removed', reason: 'you removed it; create-only files are not recreated', state: 'drop' };
    return onDisk === next ? { kind: 'unchanged', state: 'next' } : { kind: 'keep', reason: 'create-only files are never updated', state: 'base' };
  }

  if (onDisk === undefined) {
    return next === base
      ? { kind: 'kept-removed', reason: 'you removed it and the template did not change it', state: 'drop' }
      : { kind: 'conflict', reason: 'you deleted it but the template changed it', state: 'base' };
  }
  if (onDisk === next) return onDisk === base ? { kind: 'unchanged', state: 'next' } : { kind: 'converged', reason: 'you already made the same change', state: 'next' };
  if (onDisk === base) return { kind: 'update', state: 'next' };
  if (next === base) return { kind: 'keep', reason: 'you changed it and the template did not', state: 'base' };
  return { kind: 'conflict', reason: 'you changed it and the template changed it', state: 'base' };
}
