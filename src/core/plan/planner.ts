import { ConflictError } from '../../errors/index.js';
import { isMergeable, mergeContent } from '../merge/index.js';
import type { RenderedFile, SkippedFile } from '../render/renderer.js';
import { sha256Hex } from '../util/hash.js';
import type { DiskEntry } from './inspect.js';

export type OpKind = 'create' | 'update' | 'merge' | 'unchanged' | 'conflict' | 'skip';

export interface PlanOp {
  readonly path: string;
  readonly kind: OpKind;
  readonly reason?: string;
  /** Present for every kind except `skip`. */
  readonly file?: RenderedFile;
  /** SHA-256 of the content this op would leave on disk. */
  readonly hash?: string;
  /** A conflict that `--force` must never override (symlinks, directories in the way). */
  readonly unforceable?: boolean;
  /** Forge bookkeeping such as .forge/state.json; hidden from the default plan view. */
  readonly internal?: boolean;
}

export interface Plan {
  readonly ops: readonly PlanOp[];
}

export interface PlanInput {
  readonly files: readonly RenderedFile[];
  readonly skipped: readonly SkippedFile[];
  readonly disk: ReadonlyMap<string, DiskEntry>;
  /** Hashes Forge recorded the last time it wrote each file. */
  readonly previous: Readonly<Record<string, string>>;
}

function classify(file: RenderedFile, entry: DiskEntry, previousHash: string | undefined, internal: boolean): PlanOp {
  const hash = sha256Hex(file.content);
  const base = { path: file.path, file, hash, ...(internal ? { internal: true } : {}) };
  switch (entry.kind) {
    case 'missing':
      return { ...base, kind: 'create' };
    case 'blocked':
      return { ...base, kind: 'conflict', reason: entry.reason, unforceable: true };
    case 'dir':
      return { ...base, kind: 'conflict', reason: 'a directory exists at this path', unforceable: true };
    case 'file': {
      if (isMergeable(file.mergeStrategy)) {
        const merged = mergeContent(file.mergeStrategy, new TextDecoder().decode(entry.content), new TextDecoder().decode(file.content));
        if (!merged.ok) return { ...base, kind: 'conflict', reason: `cannot merge: ${merged.reason}` };
        const content = new TextEncoder().encode(merged.content);
        const mergedHash = sha256Hex(content);
        if (mergedHash === entry.hash) return { ...base, kind: 'unchanged' };
        return { ...base, file: { ...file, content }, hash: mergedHash, kind: 'merge' };
      }
      if (entry.hash === hash) return { ...base, kind: 'unchanged' };
      if (file.mergeStrategy === 'overwrite' && previousHash === entry.hash) return { ...base, kind: 'update' };
      return {
        ...base,
        kind: 'conflict',
        reason: previousHash === undefined ? 'exists and was not generated by Forge' : 'was modified after Forge generated it',
      };
    }
  }
}

/** Pure: compares rendered output with a disk snapshot and the previously recorded hashes. */
export function createPlan(input: PlanInput): Plan {
  const ops: PlanOp[] = input.files.map((file) =>
    classify(file, input.disk.get(file.path) ?? { kind: 'missing' }, input.previous[file.path], false),
  );
  for (const skipped of input.skipped) ops.push({ path: skipped.sourcePath, kind: 'skip', reason: skipped.reason });
  ops.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
  return { ops };
}

/** Add a file Forge fully owns (never a user conflict) to a plan. Used for .forge/state.json. */
export function withOwnedFile(plan: Plan, file: RenderedFile, entry: DiskEntry): Plan {
  const hash = sha256Hex(file.content);
  let op: PlanOp;
  if (entry.kind === 'file') {
    op = { path: file.path, file, hash, internal: true, kind: entry.hash === hash ? 'unchanged' : 'update' };
  } else if (entry.kind === 'missing') {
    op = { path: file.path, file, hash, internal: true, kind: 'create' };
  } else {
    op = classify(file, entry, undefined, true);
  }
  return { ops: [...plan.ops, op] };
}

/**
 * Present overwritable conflicts as updates. Used when the user passed --force, so the plan
 * and summary describe what actually happens. Blocked paths stay conflicts.
 */
export function resolveForcedConflicts(plan: Plan): Plan {
  return {
    ops: plan.ops.map((op) =>
      op.kind === 'conflict' && op.unforceable !== true
        ? { ...op, kind: 'update' as const, reason: `overwrites local changes; ${op.reason ?? 'conflict'}; backup saved` }
        : op,
    ),
  };
}

export interface PlanSummary {
  readonly create: number;
  readonly update: number;
  readonly merge: number;
  readonly unchanged: number;
  readonly conflict: number;
  readonly skip: number;
}

export function summarize(plan: Plan): PlanSummary {
  const counts = { create: 0, update: 0, merge: 0, unchanged: 0, conflict: 0, skip: 0 };
  for (const op of plan.ops) if (op.internal !== true) counts[op.kind] += 1;
  return counts;
}

export function hasChanges(plan: Plan): boolean {
  return plan.ops.some((op) => op.kind === 'create' || op.kind === 'update' || op.kind === 'merge' || op.kind === 'conflict');
}

const MAX_LISTED = 10;

/** Throw ConflictError unless every conflict may be overwritten. Blocked paths can never be overwritten. */
export function assertResolvable(plan: Plan, options: { readonly force: boolean }): void {
  const conflicts = plan.ops.filter((op) => op.kind === 'conflict');
  const blocked = conflicts.filter((op) => op.unforceable === true);
  const offending = options.force ? blocked : conflicts;
  if (offending.length === 0) return;

  const lines = offending.slice(0, MAX_LISTED).map((op) => `  ${op.path}: ${op.reason ?? 'conflict'}`);
  if (offending.length > MAX_LISTED) lines.push(`  ...and ${offending.length - MAX_LISTED} more`);
  const isBlocked = blocked.length > 0 && options.force;
  throw new ConflictError(
    `${isBlocked ? 'Cannot write' : 'Refusing to overwrite'} ${offending.length} path${offending.length === 1 ? '' : 's'}:\n${lines.join('\n')}`,
    {
      code: isBlocked ? 'FORGE_E_BLOCKED_PATH' : 'FORGE_E_CONFLICT',
      hint: isBlocked
        ? 'Remove or rename the offending paths, then re-run. --force never overrides symbolic links or directories.'
        : 'Review your changes, then re-run with --force to overwrite. Previous contents are saved under .forge/backup/.',
    },
  );
}
