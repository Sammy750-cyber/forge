import { describe, expect, it } from 'vitest';
import { MemoryFileSystem } from '../src/adapters/memory-fs.js';
import { inspectPath, snapshotDisk, type DiskEntry } from '../src/core/plan/inspect.js';
import { assertResolvable, createPlan, hasChanges, resolveForcedConflicts, summarize, withOwnedFile } from '../src/core/plan/planner.js';
import type { RenderedFile } from '../src/core/render/renderer.js';
import { sha256Hex } from '../src/core/util/hash.js';
import { ConflictError } from '../src/errors/index.js';

const enc = (s: string) => new TextEncoder().encode(s);
const file = (path: string, content: string, mergeStrategy: 'overwrite' | 'none' = 'overwrite'): RenderedFile => ({
  path, content: enc(content), mode: 0o644, mergeStrategy, sourcePath: path,
});
const onDisk = (content: string): DiskEntry => ({ kind: 'file', hash: sha256Hex(enc(content)), mode: 0o644, content: enc(content) });
const kindOf = (plan: ReturnType<typeof createPlan>, path: string) => plan.ops.find((o) => o.path === path)?.kind;

describe('createPlan classification', () => {
  const plan = (disk: Record<string, DiskEntry>, previous: Record<string, string> = {}, files = [file('a', 'new')]) =>
    createPlan({ files, skipped: [], disk: new Map(Object.entries(disk)), previous });

  it('create: nothing on disk', () => {
    expect(kindOf(plan({ a: { kind: 'missing' } }), 'a')).toBe('create');
  });
  it('unchanged: disk already equals the render', () => {
    expect(kindOf(plan({ a: onDisk('new') }), 'a')).toBe('unchanged');
  });
  it('update: disk is exactly what Forge wrote last time', () => {
    expect(kindOf(plan({ a: onDisk('old') }, { a: sha256Hex(enc('old')) }), 'a')).toBe('update');
  });
  it('conflict: user edited a generated file', () => {
    const p = plan({ a: onDisk('edited') }, { a: sha256Hex(enc('old')) });
    expect(kindOf(p, 'a')).toBe('conflict');
    expect(p.ops[0]?.reason).toMatch(/modified after Forge generated/);
  });
  it('conflict: pre-existing file Forge never wrote', () => {
    const p = plan({ a: onDisk('theirs') });
    expect(p.ops[0]?.reason).toMatch(/not generated by Forge/);
  });
  it('create-only files ("none") never update, even when pristine', () => {
    const p = plan({ a: onDisk('old') }, { a: sha256Hex(enc('old')) }, [file('a', 'new', 'none')]);
    expect(kindOf(p, 'a')).toBe('conflict');
  });
  it('blocked paths and directories are unforceable conflicts', () => {
    const blocked = plan({ a: { kind: 'blocked', reason: 'a is a symbolic link' } });
    expect(blocked.ops[0]).toMatchObject({ kind: 'conflict', unforceable: true });
    expect(plan({ a: { kind: 'dir' } }).ops[0]).toMatchObject({ kind: 'conflict', unforceable: true });
  });
  it('records skips and sorts operations by path', () => {
    const p = createPlan({
      files: [file('z', '1'), file('a', '2')],
      skipped: [{ sourcePath: 'm', reason: 'off' }],
      disk: new Map(),
      previous: {},
    });
    expect(p.ops.map((o) => `${o.path}:${o.kind}`)).toEqual(['a:create', 'm:skip', 'z:create']);
  });
});

describe('plan helpers', () => {
  const base = createPlan({
    files: [file('a', 'x'), file('b', 'y')],
    skipped: [{ sourcePath: 's', reason: 'r' }],
    disk: new Map<string, DiskEntry>([['a', { kind: 'missing' }], ['b', onDisk('mine')]]),
    previous: {},
  });

  it('summarizes visible ops only', () => {
    const withState = withOwnedFile(base, file('.forge/state.json', '{}'), { kind: 'missing' });
    expect(summarize(withState)).toEqual({ create: 1, update: 0, merge: 0, unchanged: 0, conflict: 1, skip: 1 });
  });

  it('owned files are created, updated or unchanged, never user conflicts', () => {
    const state = file('.forge/state.json', '{"v":2}');
    expect(withOwnedFile(base, state, { kind: 'missing' }).ops.at(-1)?.kind).toBe('create');
    expect(withOwnedFile(base, state, onDisk('{"v":1}')).ops.at(-1)?.kind).toBe('update');
    expect(withOwnedFile(base, state, onDisk('{"v":2}')).ops.at(-1)?.kind).toBe('unchanged');
    expect(withOwnedFile(base, state, { kind: 'dir' }).ops.at(-1)).toMatchObject({ kind: 'conflict', unforceable: true });
  });

  it('hasChanges is false only when everything is unchanged or skipped', () => {
    expect(hasChanges(base)).toBe(true);
    const quiet = createPlan({ files: [file('a', 'x')], skipped: [], disk: new Map([['a', onDisk('x')]]), previous: {} });
    expect(hasChanges(quiet)).toBe(false);
  });

  it('assertResolvable: conflicts block unless forced; blocked paths always block', () => {
    expect(() => assertResolvable(base, { force: false })).toThrow(ConflictError);
    expect(() => assertResolvable(base, { force: true })).not.toThrow();
    const blocked = createPlan({ files: [file('a', 'x')], skipped: [], disk: new Map<string, DiskEntry>([['a', { kind: 'blocked', reason: 'a is a symbolic link' }]]), previous: {} });
    try {
      assertResolvable(blocked, { force: true });
      expect.unreachable();
    } catch (error) {
      expect((error as ConflictError).code).toBe('FORGE_E_BLOCKED_PATH');
    }
  });

  it('caps the conflict listing', () => {
    const many = Array.from({ length: 15 }, (_, i) => file(`f${String(i).padStart(2, '0')}`, 'n'));
    const disk = new Map(many.map((f) => [f.path, onDisk('theirs')] as const));
    try {
      assertResolvable(createPlan({ files: many, skipped: [], disk, previous: {} }), { force: false });
      expect.unreachable();
    } catch (error) {
      expect((error as Error).message).toMatch(/and 5 more/);
    }
  });

  it('resolveForcedConflicts presents overwritable conflicts as updates', () => {
    const resolved = resolveForcedConflicts(base);
    expect(kindOf(resolved, 'b')).toBe('update');
    expect(resolved.ops.find((o) => o.path === 'b')?.reason).toMatch(/backup saved/);
  });
});

describe('inspectPath / snapshotDisk', () => {
  it('describes files, directories, missing paths and symlinks without following links', async () => {
    const fs = new MemoryFileSystem();
    fs.seed({ '/r/a.txt': 'hello', '/r/d/inner': 'x', '/outside/secret': 's' });
    fs.symlink('/r/link', '/outside');
    fs.symlink('/r/filelink', '/outside/secret');
    expect(await inspectPath(fs, '/r', 'a.txt')).toMatchObject({ kind: 'file' });
    expect(await inspectPath(fs, '/r', 'd')).toEqual({ kind: 'dir' });
    expect(await inspectPath(fs, '/r', 'nope/deeper')).toEqual({ kind: 'missing' });
    expect(await inspectPath(fs, '/r', 'link/secret')).toMatchObject({ kind: 'blocked', reason: expect.stringContaining('link') });
    expect(await inspectPath(fs, '/r', 'filelink')).toMatchObject({ kind: 'blocked' });
    expect(await inspectPath(fs, '/r', 'a.txt/child')).toMatchObject({ kind: 'blocked' });
  });

  it('treats everything as missing when the root does not exist', async () => {
    const snap = await snapshotDisk(new MemoryFileSystem(), '/nope', ['a', 'b/c']);
    expect([...snap.values()]).toEqual([{ kind: 'missing' }, { kind: 'missing' }]);
  });
});
